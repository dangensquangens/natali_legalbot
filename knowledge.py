def law(key: str) -> LegalNorm:
    return NORMS[key]


def rule(*groups: str) -> tuple[tuple[str, ...], ...]:
    """В каждой группе знак | разделяет равнозначные выражения, * обозначает начало слова."""
    return tuple(tuple(group.split("|")) for group in groups)


